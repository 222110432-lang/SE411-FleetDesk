const base = '/api/computers'

export class ApiError extends Error {
  constructor(message, status, errors = {}) {
    super(message)
    this.name = 'ApiError'
    this.status = status
    this.errors = errors
  }
}

async function request(path = '', options = {}) {
  let response
  try {
    response = await fetch(`${base}${path}`, {
      ...options,
      headers: { 'Content-Type': 'application/json', ...options.headers },
    })
  } catch (error) {
    if (error.name === 'AbortError') throw error
    throw new ApiError('Cannot reach the server. Check your connection and try again.', 0)
  }
  if (response.status === 204) return null
  let body
  try {
    body = await response.json()
  } catch {
    throw new ApiError(
      'The server returned an unreadable response. Please try again.',
      response.status,
    )
  }
  if (!response.ok)
    throw new ApiError(
      body.message || 'The request failed. Please try again.',
      response.status,
      body.errors,
    )
  return body
}

// Only send fields accepted by the API; IDs are generated by the backend.
function payload(values) {
  const keys = [
    'tag',
    'name',
    'serial',
    'type',
    'status',
    'department',
    'assignedTo',
    'location',
    'purchaseDate',
    'cost',
    'notes',
  ]
  return JSON.stringify(
    Object.fromEntries(
      keys.map((key) => [key, key === 'cost' ? Number(values[key]) : values[key]]),
    ),
  )
}

export const computerApi = {
  list(
    { page = 0, size = 5, query = '', status = '', department = '', sort = 'tag' } = {},
    signal,
  ) {
    const params = new URLSearchParams({ page, size, q: query, sort })
    if (status && status !== 'All statuses') params.set('status', status)
    if (department && department !== 'All departments') params.set('department', department)
    return request(`?${params}`, { signal })
  },
  get: (id, signal) => request(`/${encodeURIComponent(id.trim())}`, { signal }),
  summary: (signal) => request('/summary', { signal }),
  create: (values) => request('', { method: 'POST', body: payload(values) }),
  update: (id, values) =>
    request(`/${encodeURIComponent(id)}`, { method: 'PUT', body: payload(values) }),
  remove: (id) => request(`/${encodeURIComponent(id)}`, { method: 'DELETE' }),
}
